import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const W = require("../docs/play/weft8.js");
const root = path.join(import.meta.dirname, "..");
const corpus = JSON.parse(fs.readFileSync(path.join(root, "corpus.json"), "utf8"));

let out = "/* GENERATED by tools/gen-corpus.mjs — do not edit. */\n#ifndef CORPUS_H\n#define CORPUS_H\n#include <stdint.h>\n\n";
const names = [];
corpus.programs.forEach((p, i) => {
  const a = W.assemble(p.source);
  if (a.errors.length) throw new Error(p.id + ": " + JSON.stringify(a.errors));
  names.push("p" + i);
  out += "static const uint8_t prog_" + i + "[] = {" + a.all.join(",") + "};\n";
});
out += "\ntypedef struct { const char *id; const uint8_t *rom; int len; } corpus_entry;\n";
out += "static const corpus_entry CORPUS[] = {\n";
corpus.programs.forEach((p, i) => {
  out += '  {"' + p.id + '", prog_' + i + ", sizeof(prog_" + i + ")},\n";
});
out += "};\n#define CORPUS_N " + corpus.programs.length + "\n\n#endif\n";
fs.writeFileSync(path.join(root, "c", "corpus.h"), out);
console.log("wrote c/corpus.h — " + corpus.programs.length + " programs");
